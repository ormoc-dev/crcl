/**
 * Reads .env (and process.env on Vercel) → writes js/config.js
 * Usage: node scripts/sync-env.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const envPath = path.join(root, '.env')
const outPath = path.join(root, 'js', 'config.js')

function loadDotEnv(file) {
  if (!fs.existsSync(file)) return {}
  const out = {}
  for (const raw of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const line = raw.trim()
    if (!line || line.startsWith('#')) continue
    const eq = line.indexOf('=')
    if (eq < 1) continue
    const key = line.slice(0, eq).trim()
    let val = line.slice(eq + 1).trim()
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1)
    }
    out[key] = val
  }
  return out
}

const fileEnv = loadDotEnv(envPath)
const get = (key, fallback = '') =>
  String(process.env[key] || fileEnv[key] || fallback).trim()

const supabaseUrl = get('VITE_SUPABASE_URL') || get('SUPABASE_URL')
const supabaseAnonKey = get('VITE_SUPABASE_ANON_KEY') || get('SUPABASE_ANON_KEY')

const missing = []
if (!supabaseUrl || supabaseUrl.includes('YOUR_PROJECT') || supabaseUrl.includes('your-project')) {
  missing.push('VITE_SUPABASE_URL')
}
if (!supabaseAnonKey || supabaseAnonKey.includes('YOUR_') || supabaseAnonKey.includes('your-anon')) {
  missing.push('VITE_SUPABASE_ANON_KEY')
}

if (missing.length) {
  console.error(
    `sync-env: missing ${missing.join(', ')}.\n` +
      `Add them to .env (local) or Vercel Environment Variables, then re-run.`,
  )
  process.exit(1)
}

const esc = (s) => JSON.stringify(String(s))
const source = fs.existsSync(envPath) ? '.env' : 'process.env'

const contents = `/**
 * AUTO-GENERATED by scripts/sync-env.mjs from ${source}.
 * Do not edit by hand — change .env (or Vercel env vars) and run: npm run sync-env
 *
 * Supabase publishable/anon key is safe in the client (RLS protects data).
 * Never put sb_secret_ / service_role keys in this file.
 */

export const config = {
  supabaseUrl: ${esc(supabaseUrl)},
  supabaseAnonKey: ${esc(supabaseAnonKey)},
}
`

fs.mkdirSync(path.dirname(outPath), { recursive: true })
fs.writeFileSync(outPath, contents, 'utf8')
console.log(`sync-env: wrote ${path.relative(root, outPath)}`)
